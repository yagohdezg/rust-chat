/// Whether `password` is one of the bundled common passwords. Case and
/// surrounding whitespace are ignored, because those variants ("Password",
/// " letmein ") are as common as the canonical spelling.
pub fn is_breached(password: &str) -> bool {
    let candidate = password.trim().to_ascii_lowercase();
    BREACHED.iter().any(|known| *known == candidate)
}
